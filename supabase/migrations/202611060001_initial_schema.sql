create extension if not exists pgcrypto;

create table if not exists public.produtos (
    id uuid primary key default gen_random_uuid(),
    nome text not null,
    codigo text not null unique,
    preco_peca_branca numeric(10, 2) not null check (preco_peca_branca >= 0),
    fotos text[] not null default '{}',
    tags text[] not null default '{}',
    ativo boolean not null default true,
    destaque boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.precos_decoracao (
    id bigint generated by default as identity primary key,
    quantidade integer not null check (quantidade in (10, 20, 30, 40, 50, 100, 200)),
    cores smallint not null check (cores between 1 and 6),
    valor numeric(10, 2) not null check (valor >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (quantidade, cores)
);

create table if not exists public.perfis_admin (
    user_id uuid primary key references auth.users (id) on delete cascade,
    administrador_principal boolean not null default false,
    ativo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create or replace function public.usuario_admin_autorizado()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
    select exists (
        select 1
        from public.perfis_admin
        where user_id = auth.uid()
          and ativo = true
    );
$$;

create or replace function public.usuario_admin_principal()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
    select exists (
        select 1
        from public.perfis_admin
        where user_id = auth.uid()
          and ativo = true
          and administrador_principal = true
    );
$$;

create or replace function public.atualizar_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists produtos_atualizar_updated_at on public.produtos;
create trigger produtos_atualizar_updated_at
before update on public.produtos
for each row execute function public.atualizar_updated_at();

drop trigger if exists precos_decoracao_atualizar_updated_at on public.precos_decoracao;
create trigger precos_decoracao_atualizar_updated_at
before update on public.precos_decoracao
for each row execute function public.atualizar_updated_at();

drop trigger if exists perfis_admin_atualizar_updated_at on public.perfis_admin;
create trigger perfis_admin_atualizar_updated_at
before update on public.perfis_admin
for each row execute function public.atualizar_updated_at();

